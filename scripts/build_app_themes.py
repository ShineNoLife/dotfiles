#!/usr/bin/env python3
"""Build app themes from Kitty's palette and the shared bar CSS accents."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / '.config'


def build():
    kitty = dict(re.findall(r'^([a-z0-9_]+)\s+(#[0-9a-fA-F]{6})\s*$',
                           (CONFIG / 'themes/shine-theme-kitty.conf').read_text(), re.M))
    css = dict(re.findall(r'@define-color\s+(\w+)\s+(#[0-9a-fA-F]{6});',
                         (CONFIG / 'themes/shine-theme.css').read_text()))
    p = dict(bg=kitty['background'], fg=kitty['foreground'], surface='#272e33',
             raised=kitty['active_tab_background'], border='#4a555b',
             muted=kitty['color15'], primary=css['primary'], blue=css['secondary'],
             orange=css['accent'], red=kitty['color1'], yellow=kitty['color3'],
             purple=kitty['color5'], selection=kitty['selection_background'],
             selection_fg=kitty['selection_foreground'])
    p = {k: v.lower() for k, v in p.items()}
    named = {
        'theme_bg_color': 'bg', 'theme_fg_color': 'fg', 'theme_base_color': 'bg',
        'theme_text_color': 'fg', 'theme_selected_bg_color': 'selection',
        'theme_selected_fg_color': 'selection_fg', 'insensitive_bg_color': 'surface',
        'insensitive_fg_color': 'muted', 'insensitive_base_color': 'surface',
        'theme_unfocused_bg_color': 'bg', 'theme_unfocused_fg_color': 'fg',
        'theme_unfocused_base_color': 'bg', 'theme_unfocused_text_color': 'fg',
        'theme_unfocused_selected_bg_color': 'selection',
        'theme_unfocused_selected_fg_color': 'selection_fg',
        'borders': 'border', 'unfocused_borders': 'border',
        'warning_color': 'yellow', 'error_color': 'red', 'success_color': 'primary',
        'accent_bg_color': 'primary', 'accent_fg_color': 'bg', 'accent_color': 'primary',
        'window_bg_color': 'bg', 'window_fg_color': 'fg', 'view_bg_color': 'bg',
        'view_fg_color': 'fg', 'headerbar_bg_color': 'surface', 'headerbar_fg_color': 'fg',
        'headerbar_backdrop_color': 'surface', 'sidebar_bg_color': 'surface',
        'sidebar_fg_color': 'fg', 'sidebar_backdrop_color': 'surface',
        'card_bg_color': 'raised', 'card_fg_color': 'fg',
        'popover_bg_color': 'surface', 'popover_fg_color': 'fg',
        'dialog_bg_color': 'surface', 'dialog_fg_color': 'fg',
        'content_view_bg': 'bg', 'text_view_bg': 'bg', 'placeholder_text_color': 'muted',
        'wm_focused_title': 'fg', 'wm_unfocused_title': 'muted',
        'wm_focused_bg': 'surface', 'wm_unfocused_bg': 'surface',
    }
    header = '/* Generated by scripts/build_app_themes.py. Edit the Kitty/shared CSS palette, then rebuild. */\n'
    definitions = ''.join(f'@define-color {name} {p[key]};\n' for name, key in named.items())
    gtk3 = header + definitions + '''
.background, window, dialog { background-color: @theme_bg_color; color: @theme_fg_color; }
headerbar, .titlebar, .primary-toolbar { background: @headerbar_bg_color; color: @headerbar_fg_color; }
.view, treeview, iconview, textview, textview text, entry, .content-view {
  background-color: @theme_base_color; color: @theme_text_color;
}
.sidebar, .navigation-sidebar, .sidebar .view { background-color: @sidebar_bg_color; color: @sidebar_fg_color; }
button, spinbutton, combobox { color: @theme_fg_color; }
button:not(.flat) { background-color: @card_bg_color; background-image: none; border-color: @borders; }
button:hover { background-image: none; background-color: alpha(@accent_bg_color, 0.12); }
button:checked, button:active, button.suggested-action, switch:checked,
check:checked, check:indeterminate, radio:checked, progressbar progress, scale highlight {
  background-image: none; background-color: @accent_bg_color; color: @accent_fg_color; border-color: @accent_bg_color;
}
button.destructive-action { background-image: none; background-color: @error_color; color: @accent_fg_color; }
entry:focus, spinbutton:focus { border-color: @accent_bg_color; }
selection, .view:selected, treeview.view:selected, row:selected,
textview text selection, entry selection {
  background-color: @theme_selected_bg_color; color: @theme_selected_fg_color;
}
menu, menu .view, popover, popover.background, tooltip, tooltip.background {
  background-color: @popover_bg_color; color: @popover_fg_color;
}
menuitem:hover { background-color: alpha(@accent_bg_color, 0.15); color: @accent_color; }
*:link { color: @accent_color; }
*:disabled { color: @insensitive_fg_color; }
'''
    variables = {
        'accent-bg-color': 'primary', 'accent-fg-color': 'bg', 'accent-color': 'primary',
        'destructive-bg-color': 'red', 'destructive-fg-color': 'bg', 'destructive-color': 'red',
        'success-bg-color': 'primary', 'success-fg-color': 'bg', 'success-color': 'primary',
        'warning-bg-color': 'yellow', 'warning-fg-color': 'bg', 'warning-color': 'yellow',
        'error-bg-color': 'red', 'error-fg-color': 'bg', 'error-color': 'red',
        'window-bg-color': 'bg', 'window-fg-color': 'fg',
        'view-bg-color': 'bg', 'view-fg-color': 'fg',
        'headerbar-bg-color': 'surface', 'headerbar-fg-color': 'fg',
        'headerbar-backdrop-color': 'surface',
        'sidebar-bg-color': 'surface', 'sidebar-fg-color': 'fg', 'sidebar-backdrop-color': 'surface',
        'secondary-sidebar-bg-color': 'raised', 'secondary-sidebar-fg-color': 'fg',
        'secondary-sidebar-backdrop-color': 'raised',
        'card-bg-color': 'raised', 'card-fg-color': 'fg',
        'dialog-bg-color': 'surface', 'dialog-fg-color': 'fg',
        'popover-bg-color': 'surface', 'popover-fg-color': 'fg',
        'overview-bg-color': 'bg', 'overview-fg-color': 'fg',
        'thumbnail-bg-color': 'surface', 'thumbnail-fg-color': 'fg',
        'active-toggle-bg-color': 'primary', 'active-toggle-fg-color': 'bg',
    }
    gtk4 = header + definitions + '\n/* Keep GTK/libadwaita layouts; override palette tokens only. */\n:root, window, popover, tooltip {\n'
    gtk4 += ''.join(f'  --{name}: {p[key]};\n' for name, key in variables.items())
    gtk4 += '  --headerbar-shade-color: rgb(0 0 0 / 20%);\n  --sidebar-border-color: rgb(0 0 0 / 20%);\n}\n'
    gtk4 += f'''selection {{ background-color: {p['selection']}; color: {p['selection_fg']}; }}
'''
    outputs = {
        CONFIG / 'themes/shine-gtk3.css': gtk3,
        CONFIG / 'themes/shine-gtk4.css': gtk4,
        CONFIG / 'gtk-3.0/gtk.css': '@import url("../themes/shine-gtk3.css");\n',
        CONFIG / 'gtk-4.0/gtk.css': '@import url("../themes/shine-gtk4.css");\n',
        CONFIG / 'gtk-4.0/gtk-dark.css': '@import url("gtk.css");\n',
        ROOT / '.themes/Shine-Everforest/index.theme': '''[Desktop Entry]
Type=X-GNOME-Metatheme
Name=Shine Everforest
Comment=Custom Kitty and bar palette

[X-GNOME-Metatheme]
GtkTheme=Shine-Everforest
IconTheme=Papirus-Dark
''',
        ROOT / '.themes/Shine-Everforest/gtk-3.0/gtk.css': '@import url("../../Everforest-BL-LB-Dark/gtk-3.0/gtk.css");\n',
        ROOT / '.themes/Shine-Everforest/gtk-3.0/gtk-dark.css': '@import url("gtk.css");\n',
    }
    # QPalette roles 0..21, including Qt 6 Accent; Qt 5 ignores the extra role.
    roles = ['fg','surface','border','raised','bg','border','fg','fg','fg','bg',
             'bg','bg','selection','selection_fg','blue','purple','surface','bg',
             'surface','fg','muted','primary']
    qt_colors = '[ColorScheme]\n'
    for group in ('active', 'disabled', 'inactive'):
        colors = [p[key] for key in roles]
        if group == 'disabled':
            for i in (0, 6, 8, 13, 19): colors[i] = p['muted']
        qt_colors += group + '_colors=' + ', '.join('#ff' + c[1:] for c in colors) + '\n'
    palette_path = CONFIG / 'qt6ct/colors/Shine-Everforest.conf'
    outputs[palette_path] = qt_colors
    for version in (5, 6):
        outputs[CONFIG / f'qt{version}ct/qt{version}ct.conf'] = f'''[Appearance]
color_scheme_path={palette_path}
custom_palette=true
icon_theme=Papirus-Dark
standard_dialogs=default
style=Fusion

[Fonts]
general="Adwaita Sans,11,-1,5,50,0,0,0,0,0"
fixed="JetBrainsMono Nerd Font,11,-1,5,50,0,0,0,0,0"
'''
    def rgb(key):
        color = p[key][1:]
        return [int(color[i:i+2],16) for i in (0, 2, 4)]
    colors = {name: rgb(key) for name, key in {
        'frame':'bg', 'frame_inactive':'bg', 'frame_incognito':'bg', 'frame_incognito_inactive':'bg',
        'toolbar':'surface', 'tab_text':'fg', 'tab_background_text':'muted',
        'bookmark_text':'fg', 'ntp_background':'bg', 'ntp_text':'fg', 'ntp_link':'primary',
        'button_background':'surface', 'toolbar_button_icon':'fg',
        'toolbar_text':'fg', 'omnibox_background':'bg', 'omnibox_text':'fg',
        'toolbar_top_separator':'border', 'toolbar_bottom_separator':'border',
        'toolbar_vertical_separator':'border', 'tab_line':'primary',
    }.items()}
    manifest = dict(manifest_version=3, name='Shine Everforest', version='1.0.0',
                    description='Your Kitty and bar colors: dark background, cream text, green accents.',
                    theme=dict(colors=colors, properties={'ntp_logo_alternate':1}))
    outputs[CONFIG / 'edge-theme/manifest.json'] = json.dumps(manifest, indent=2) + '\n'
    outputs[CONFIG / 'microsoft-edge-stable-flags.conf'] = f'--load-extension={CONFIG / "edge-theme"}\n--force-dark-mode\n'
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in build().items():
        if args.check:
            if not path.is_file() or path.is_symlink() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            # Replace old GTK 4 symlinks, not the original vendored theme files.
            if path.is_symlink(): path.unlink()
            path.write_text(content)
    if stale:
        print('Rebuild app themes: ' + ', '.join(stale), file=sys.stderr)
        return 1
    print('App themes match Kitty and shared CSS.' if args.check else 'Built GTK 3/4, Qt 5/6 and Edge themes.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
